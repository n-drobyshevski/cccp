// Small helpers the common tool steps share: the generated-file header lines, the pending path of a
// source key, the flat name of a legacy stylesheet, the order the source's files are read in, and
// the sanitising of source-derived text before it is printed, and the pages a page link may name.

import { pagesOf } from "../codemod/markup.mjs";
import { appPages } from "../frameLinks.mjs";

/**
 * The pages the migrated app has, each with its kit path, for the page-link rule (frameLinks.mjs
 * pageRewrite): a classic source's pages, the plan's maps.pages, the inventory's one-segment hash
 * routes.
 * @param {import("../apply.mjs").StepContext} ctx
 */
export function pagesFor(ctx) {
  const pages = /** @type {Record<string, unknown> | undefined} */ (/** @type {Record<string, unknown>} */ (ctx.plan.maps)["pages"]);
  return appPages({ classic: ctx.plan.profile === "classic" ? pagesOf(ctx.tree) : [], pages: pages ?? {}, routes: ctx.inv.routes ?? [] });
}

/** The directory parked source files go to. */
export const PENDING = ".migrate/pending/";

/** @param {string} key a source key @returns {string} */
export const pendingPath = (key) => PENDING + key;

/**
 * The header comment of a generated script file.
 * @param {string} stepId @param {string} from a source key or a short description
 */
export const jsHeader = (stepId, from) => "// Generated by gas-kit migrate (" + stepId + ") from " + oneLine(from) + "; edit freely.\n";

/**
 * A source key made safe for a one-line comment: a source file name may hold U+2028 or U+2029,
 * which end a line comment in JavaScript, so they and any other line break become a space.
 * @param {string} s
 */
export const oneLine = (s) => s.replace(/[\r\n\u0085\u2028\u2029]/g, " ");

/**
 * Text that came from the source (a note, a failure, a step title) made safe to print: every C0 and
 * C1 control character but tab and line feed (ESC starts the terminal's CSI and OSC sequences, which
 * can rewrite the screen or the window title), and the bidirectional overrides, become a space.
 * @param {string} s
 */
export const termSafe = (s) => String(s).replace(/[\u0000-\u0008\u000b-\u001f\u007f-\u009f\u202a-\u202e\u2066-\u2069]/g, " ");

/**
 * termSafe on one line: line breaks become spaces too, so source text cannot draw a line of its own.
 * @param {string} s
 */
export const termLine = (s) => termSafe(oneLine(s)).replace(/[\t\n]/g, " ");

/**
 * The header comment of a generated stylesheet.
 * @param {string} stepId @param {string} from
 */
export const cssHeader = (stepId, from) => "/* Generated by gas-kit migrate (" + stepId + ") from " + oneLine(from).replace(/\*\//g, "* /") + "; edit freely. */\n";

/**
 * The flat file name a source stylesheet gets under src/client/styles/legacy/: its key with every
 * run of characters outside [A-Za-z0-9] turned into one dash, the extension dropped. A key of an
 * inline <style> block carries its index.
 * @param {string} key
 */
export function legacyName(key) {
  const stem = key.replace(/\.(css|html)$/i, "").replace(/^(?:src\/client|src|client)\//, "");
  const flat = stem.replace(/[^A-Za-z0-9]+/g, "-").replace(/^-+|-+$/g, "").toLowerCase();
  return (flat || "style") + (/\.html$/i.test(key) ? "-inline" : "");
}

/** @param {string} key @returns {number} 0 for the source root, 1 for a shared root */
export const rootRank = (key) => (key.startsWith("@") ? 1 : 0);

/** Source keys in the order the steps read them: source root first, then by key. @param {string[]} keys */
export const sortedKeys = (keys) => [...keys].sort((a, b) => rootRank(a) - rootRank(b) || (a < b ? -1 : a > b ? 1 : 0));

/**
 * Throw a clear error naming the step when a template marker is gone.
 * @param {string} stepId @param {string} what
 * @returns {never}
 */
export function drift(stepId, what) {
  throw new Error(stepId + ": the template drifted: " + what);
}
