// The server-park step (el-builder): the endpoint bodies stay parked (the park step copied
// dist/entry.js and src/server/*.ts to .migrate/pending); this step writes
// .migrate/pending/SERVER-NOTES.md, each endpoint and server global with where it lives in the
// source, under the final name rpc-surface gives it (steps/_rpcName.mjs). The profile's
// port-server agent step (in the plan) moves them into src/server/app. No live write.
import { analyze, isId, isP, isStr, strOf } from "../codemod/js.mjs";
import { finalRpcNames, templateNames } from "./_rpcName.mjs";

export const NOTES_FILE = ".migrate/pending/SERVER-NOTES.md";

/**
 * Where a name is defined in a server file: a function declaration, an api_<name> delegator, an
 * object key (an endpoint table) or an export list.
 * @param {string} text @param {string} name
 * @returns {number[]} lines
 */
function placesOf(text, name) {
  const J = analyze(text);
  /** @type {number[]} */
  const lines = [];
  for (let k = 0; k < J.toks.length; k++) {
    const t = J.toks[k];
    if (!t) continue;
    const named = (t.type === "ident" && (t.value === name || t.value === "api_" + name)) || (isStr(J, k) && strOf(J, k) === name && isP(J, k + 1, ":"));
    if (!named || isP(J, k - 1, ".")) continue;
    if (isId(J, k - 1, "function") || (isP(J, k + 1, ":") && (isP(J, k - 1, "{") || isP(J, k - 1, ","))) || (isP(J, k + 1, "(") && isP(J, J.match[k + 1] + 1, "{") && J.depth[k] === 1)) lines.push(t.line);
  }
  return [...new Set(lines)];
}

/** @param {import("../apply.mjs").StepContext} ctx */
export function run(ctx) {
  const keys = ctx.step.files.reads.filter((k) => ctx.tree.files.has(k)).sort();
  const texts = keys.map((k) => ({ key: k, text: ctx.tree.read(k) }));
  const globals = (ctx.inv.globals ?? []).filter((g) => keys.includes(g.key));
  const endpoints = [...new Set([...(ctx.inv.rpc ?? []), ...globals.filter((g) => g.kind === "endpoint").map((g) => g.name.replace(/^api_/, ""))])].sort();
  let rpc;
  try {
    rpc = finalRpcNames(ctx.inv, /** @type {Record<string, unknown>} */ (ctx.plan.maps.rpc ?? {}), templateNames(ctx.kitRoot)).names;
  } catch (e) {
    throw new Error("server-park: " + /** @type {Error} */ (e).message);
  }
  const roles = /** @type {Record<string, unknown>} */ (/** @type {Record<string, unknown>} */ (ctx.plan.maps)["roles"] ?? {});
  const lines = [
    "<!-- Generated by gas-kit migrate (" + ctx.step.id + ") from " + (keys.join(", ") || "no server file") + "; edit freely. -->",
    "# Server notes",
    "",
    "The source app's endpoints and server globals, with where each lives. The kit name is the one the",
    "endpoint has in the target (the rpc-surface step's rule: a name the template already uses becomes",
    "legacy<Name>); page code calls it by that name. The bodies are parked as they were under",
    "`.migrate/pending/` (same paths). The port-server step moves each body into",
    "`src/server/app/` behind the endpoint the rpc-surface step added to `src/server/api.ts`",
    "(owner-only until classify-roles rules on it), returning the kit envelope through `run()`.",
    "",
    "## Endpoints",
    "",
    "| endpoint | kit name | role | defined at |",
    "| --- | --- | --- | --- |",
  ];
  for (const name of endpoints) {
    const at = texts.flatMap((f) => placesOf(f.text, name).map((l) => "`" + f.key + ":" + l + "`"));
    lines.push("| `" + name + "` | `" + String(rpc[name] ?? name) + "` | " + String(roles[name] ?? "owner") + " | " + (at.join(", ") || "not found") + " |");
  }
  const other = globals.filter((g) => g.kind !== "endpoint");
  if (other.length) {
    lines.push("", "## Other server globals", "", "| global | kind | defined at |", "| --- | --- | --- |");
    for (const g of other) lines.push("| `" + g.name + "` | " + g.kind + " | `" + g.key + ":" + g.line + "` |");
    lines.push("", "A trigger keeps its global in `src/gas/entry.js` (the triggers step); `doGet` and `include` are the kit's own.");
  }
  lines.push("");
  ctx.out.write(NOTES_FILE, lines.join("\n"));
  return { notes: [endpoints.length + " endpoint(s) and " + other.length + " other global(s) listed in " + NOTES_FILE] };
}
