// The flatten-includes step (classic profile): each page doGet can serve (an html file no other file
// includes) is written to .migrate/pending/pages/<page>.html with every include('x') scriptlet
// replaced by the file it names, recursively, between begin and end markers. The include order is
// recorded in plan.maps.classicPages. A cycle in the include graph fails the step with the chain.
// Nothing goes live: the pages wait in .migrate/pending for the steps and agents after this one.
import { flatten, pagesOf } from "../codemod/markup.mjs";

/** Where a flattened page goes. @param {string} page */
export const pagePath = (page) => ".migrate/pending/pages/" + page + ".html";

/** @param {string} stepId @param {string} from */
export const htmlHeader = (stepId, from) => "<!-- Generated by gas-kit migrate (" + stepId + ") from " + from.replace(/-(?=-)/g, "- ").replace(/>/g, "&gt;") + "; edit freely. -->\n";

/** @param {import("../apply.mjs").StepContext} ctx */
export function run(ctx) {
  const pages = pagesOf(ctx.tree);
  /** @type {Record<string, { source: string, file: string, includes: string[] }>} */
  const classicPages = {};
  /** @type {string[]} */
  const notes = [];
  for (const { page, key } of pages) {
    const f = flatten(ctx.tree, key);
    ctx.out.write(pagePath(page), htmlHeader(ctx.step.id, key) + f.text);
    classicPages[page] = { source: key, file: pagePath(page), includes: f.order };
    notes.push(page + ": " + key + (f.order.length ? " with " + f.order.join(", ") : " (no includes)"));
    for (const m of f.missing) notes.push(page + ": include(" + JSON.stringify(m) + ") names no file of the source; it stays, marked");
  }
  if (!pages.length) notes.push("no page to flatten: the source has no html file that doGet could serve");
  return { notes, maps: { classicPages } };
}
