/* Extracted from the author's production Apps Script apps; adapted.
   The gallery page. The dev server bundles this file with every component module; "gallery:data"
   is generated (the module namespaces); the manifest is fetched from /gallery.json. It renders one section per component and,
   per example, one card in the light theme and one in the dark theme, then mounts the islands. */
import { html, delegate, installTips, mountIslands, renderRegion } from "@gas-kit/client";
import { errorCard, exampleView } from "./example.js";
import { uniquifyIds } from "./ids.js";
// @ts-ignore generated by the dev server (gallery.mjs)
import { moduleIndex, modules } from "gallery:data";

/** @type {any[]} */
let components = [];
const params = new URLSearchParams(window.location.search);
const filter = (params.get("c") || "").trim();
const onlyTheme = params.get("theme") === "dark" ? "dark" : params.get("theme") === "light" ? "light" : "";
const themes = onlyTheme ? [onlyTheme] : ["light", "dark"];

function pick() {
  if (!filter) return components;
  const f = filter.toLowerCase();
  const exact = components.filter((c) => c.name.toLowerCase() === f);
  return exact.length ? exact : components.filter((c) => c.name.toLowerCase().indexOf(f) >= 0);
}
/** @type {any[]} */
let shown = [];
/** The motion choice for this page: data-motion on the root element, never stored. @type {"system" | "reduce" | "full"} */
let motion = "system";

/** Every island object the modules export, by the name a view puts in data-mount. */
const registry = /** @type {Record<string, any>} */ ({});
modules.forEach((/** @type {Record<string, any>} */ m) => {
  Object.keys(m).forEach((k) => {
    const v = m[k];
    if (v && typeof v === "object" && typeof v.mount === "function") {
      registry[k] = v;
      const short = k.replace(/(Island|Def)$/, "");
      if (!(short in registry)) registry[short] = v;
    }
  });
});

/** The exports an example can name: its own module first, then every other module. @param {any} c */
function scopeFor(c) {
  const scope = /** @type {Record<string, any>} */ ({});
  const own = modules[moduleIndex[c.module]] || {};
  const add = (/** @type {Record<string, any>} */ m) => {
    Object.keys(m).forEach((k) => {
      if (/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(k) && !(k in scope)) scope[k] = m[k];
    });
  };
  add(own);
  modules.forEach(add);
  return scope;
}

/** @param {any} c */
function sectionView(c) {
  return html`<section class="gal-section" id="${"c-" + c.name}" data-component="${c.name}">
<h2>${c.name}${c.kind === "block" ? html` <span class="gal-kind">block</span>` : null}</h2>
<p class="gal-summary">${c.summary}</p>
<p class="gal-a11y"><strong>Accessibility.</strong> ${c.a11y}</p>
${c.examples.map((/** @type {any} */ ex) => html`<article class="gal-state" data-state="${ex.state}">
<h3>${ex.state}</h3>
<div class="gal-pair">${themes.map((t) => html`<div class="gal-cell"><p class="gal-theme-label">${t} <button type="button" class="gal-replay" data-replay aria-label="${"Replay " + c.name + " " + ex.state + " (" + t + ")"}">Replay</button></p><div class="gal-card" data-gallery-card data-theme="${t}" data-component="${c.name}" data-state="${ex.state}"></div></div>`)}</div>
<pre class="gal-code"><code>${ex.code}</code></pre>
</article>`)}
</section>`;
}

function pageView() {
  const body = shown.length
    ? shown.map(sectionView)
    : html`<p class="gal-empty" role="status">No component matches "${filter}".</p>`;
  const states = shown.reduce((n, c) => n + c.examples.length, 0);
  return html`<header class="gal-head">
<h1 tabindex="-1">Component gallery</h1>
<form class="gal-filter" method="get" role="search">
<label for="gal-c">Component</label>
<input id="gal-c" name="c" value="${filter}" list="gal-names" autocomplete="off" data-k="gal-c">
<datalist id="gal-names">${components.map((c) => html`<option value="${c.name}"></option>`)}</datalist>
${onlyTheme ? html`<input type="hidden" name="theme" value="${onlyTheme}">` : null}
<button type="submit">Show</button>
<a href="?">All components</a>
<span class="gal-motion" role="group" aria-label="Motion">Motion ${["system", "reduce", "full"].map((m) => html`<button type="button" class="gal-motion__btn" data-motion-set="${m}" aria-pressed="${m === motion ? "true" : "false"}">${m}</button>`)}</span>
<span class="muted" role="status">${plural(shown.length, "component")}, ${plural(states, "state")}, ${plural(themes.length, "theme")}</span>
</form>
<nav aria-label="Components"><ul class="gal-jump">${shown.map((c) => html`<li><a href="${"#c-" + c.name}">${c.name}</a></li>`)}</ul></nav>
</header>
<main>${body}</main>`;
}

/** @param {number} n @param {string} word */
function plural(n, word) {
  return n + " " + word + (n === 1 ? "" : "s");
}

function start(/** @type {{ components: any[] }} */ manifest) {
  components = manifest.components;
  shown = pick();
  const app = document.getElementById("app");
  if (!app) return;
  renderRegion(app, pageView(), { keepFocus: false, keepScroll: false });
  /** @type {Map<string, any>} */
  const done = new Map();
  /** Render one card's example, with its own ids and radio groups. @param {Element} card @param {number} index @param {boolean} [fresh] */
  const paint = (card, index, fresh) => {
    const name = card.getAttribute("data-component");
    const state = card.getAttribute("data-state");
    const c = components.find((x) => x.name === name);
    const ex = c && c.examples.find((/** @type {any} */ x) => x.state === state);
    const key = name + "|" + state;
    if (fresh || !done.has(key)) done.set(key, ex ? exampleView(ex.code, scopeFor(c)) : errorCard("no example for this state"));
    renderRegion(card, done.get(key), { keepFocus: false, keepScroll: false });
    // Both themes of an example are on one page: give this card its own ids and radio groups, now (so
    // the next card's radios do not join this card's group) and again once the islands have mounted.
    const suffix = "--g" + index;
    uniquifyIds(card, suffix);
    mountIslands(card, registry);
    uniquifyIds(card, suffix);
  };
  const cards = Array.prototype.slice.call(document.querySelectorAll("[data-gallery-card]"));
  cards.forEach((card, index) => paint(card, index));
  // Replay: render the example again from its code, so entrances and count-ups play once more.
  delegate(app, "click", "[data-replay]", (_ev, btn) => {
    const cell = btn.closest(".gal-cell");
    const card = cell && cell.querySelector("[data-gallery-card]");
    if (card) paint(card, cards.indexOf(card), true);
  });
  // The motion control sets data-motion on this page only (the system choice removes it); it is not stored.
  delegate(app, "click", "[data-motion-set]", (_ev, btn) => {
    motion = /** @type {any} */ (btn.getAttribute("data-motion-set"));
    if (motion === "system") document.documentElement.removeAttribute("data-motion");
    else document.documentElement.setAttribute("data-motion", motion);
    Array.prototype.forEach.call(app.querySelectorAll("[data-motion-set]"), (/** @type {Element} */ b) => {
      b.setAttribute("aria-pressed", b.getAttribute("data-motion-set") === motion ? "true" : "false");
    });
  });
  // The confirm island focuses its default button on mount; the gallery must not trap the page.
  // Focus then blur the page title: that moves the sequential-focus start point out of the card, so
  // the first Tab lands on the component filter.
  const title = /** @type {any} */ (document.querySelector(".gal-head h1"));
  if (title) { title.focus(); title.blur(); }
  installTips(document.body);
  // Mounting focused and scrolled to an island; open at the top, or at the section the hash names.
  const target = window.location.hash ? document.getElementById(decodeURIComponent(window.location.hash.slice(1))) : null;
  if (target) target.scrollIntoView(); else window.scrollTo(0, 0);
  document.body.setAttribute("data-ready", "1");
}

/* The chart island loads its script from a placeholder host. The gallery stays offline: that one
   script request is pointed at an empty local script, so the island shows its unavailable state. */
(function keepOffline() {
  const head = document.head;
  const add = head.appendChild;
  /** @this {Node} @param {any} node */
  function guarded(node) {
    if (node && node.tagName === "SCRIPT" && node.src) {
      let host = "";
      try { host = new URL(node.src).hostname; } catch { /* not a URL */ }
      if (host === "example.org") node.src = "/gallery-stub.js";
    }
    return add.call(this, node);
  }
  head.appendChild = /** @type {any} */ (guarded);
})();

fetch("/gallery.json")
  .then((r) => r.json())
  .then(start)
  .catch((e) => {
    const app = document.getElementById("app");
    if (app) renderRegion(app, errorCard(String((e && e.message) || e)), { keepFocus: false, keepScroll: false });
    document.body.setAttribute("data-ready", "1");
  });
